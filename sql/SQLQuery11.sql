CREATE VIEW VW_ABATERE AS
SELECT 
ORDERID,
TRANSPORTMODE,
SHIPPINGCOST,
AVG(SHIPPINGCOST) OVER (PARTITION BY TRANSPORTMODE) AS MEDIA,
SHIPPINGCOST- AVG(SHIPPINGCOST) OVER (PARTITION BY TRANSPORTMODE) AS ABATEREA
FROM [dbo].[supply_chain_cleaned1]

CREATE OR ALTER VIEW vw_PondereDepozite_Optimizat AS
WITH DatePeDepozit AS (
    SELECT DISTINCT
        Warehouse,
        COUNT(OrderID) OVER (PARTITION BY Warehouse) AS ComenziDepozit,
        AVG(CAST(TransitDays AS DECIMAL(10,2))) OVER (PARTITION BY Warehouse) AS TimpMediuTranzitDepozit,
        COUNT(OrderID) OVER () AS TotalComenziGlobal
    FROM supply_chain_cleaned1
)
SELECT 
    Warehouse,
    ComenziDepozit,
    TimpMediuTranzitDepozit,
    CAST(ComenziDepozit * 100.0 / TotalComenziGlobal AS DECIMAL(5,2)) AS ProcentDinTotalComenzi
FROM DatePeDepozit;
GO