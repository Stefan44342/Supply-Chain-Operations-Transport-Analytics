CREATE VIEW VW_AnalizaFurnizori AS
SELECT 
SUPPLIER,
SUM(SHIPPINGCOST) AS COST_TRANSPORT,
SUM(QUANTITY) AS VOLUM_MARFA,
AVG(SHIPPINGCOST) AS COST_MEDIU_PER_COMANDA
FROM [dbo].[supply_chain_cleaned1]
GROUP BY SUPPLIER
GO

CREATE VIEW VW_TREND_LOGISTIC AS
SELECT
WAREHOUSE,
YEARMONTH,
COUNT(ORDERID) AS VOLUM_COMENZI,
SUM(SHIPPINGCOST) AS COSTURI_TOTALE
FROM [dbo].[supply_chain_cleaned1]
GROUP BY Warehouse, YearMonth

GO
CREATE VIEW VW_BESTsUPPLIER AS
WITH RANK_FURNIZORI AS(
SELECT 
SUPPLIER,
TRANSPORTMODE,
SUM(SHIPPINGCOST) AS COST_TOTAL,
RANK() OVER (PARTITION BY TRANSPORTMODE ORDER BY SUM(SHIPPINGCOST) DESC) AS POZ_CLASAMENT
FROM [dbo].[supply_chain_cleaned1]
GROUP BY SUPPLIER, TRANSPORTMODE
)
SELECT TRANSPORTMODE, SUPPLIER, COST_TOTAL, POZ_CLASAMENT FROM RANK_FURNIZORI WHERE POZ_CLASAMENT<=3

GO
CREATE VIEW VW_SUMACUMULATA AS
SELECT 
ORDERID,
ORDERDATE,
SHIPPINGCOST,
SUM(SHIPPINGCOST) OVER (ORDER BY ORDERDATE ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS COST_CUMULAT
FROM [dbo].[supply_chain_cleaned1]

GO
CREATE VIEW VW_COSTANTERIOR AS
WITH COST_LUNAR AS(
SELECT 
YEARMONTH,
SUM(SHIPPINGCOST) AS COST_PER_LUNA
FROM [dbo].[supply_chain_cleaned1]
GROUP BY YEARMONTH)
SELECT 
YEARMONTH,
COST_PER_LUNA,
LAG(COST_PER_LUNA,1) OVER (ORDER BY YEARMONTH) AS COST_LUNA_ANTERIOARA,
COST_PER_LUNA - LAG(COST_PER_LUNA,1) OVER (ORDER BY YEARMONTH) AS DIFERENTA_COST
FROM COST_LUNAR

GO
CREATE VIEW VW_TOP2_COMENZI AS
WITH CTE AS(
SELECT 
WAREHOUSE,
TRANSPORTMODE,
ORDERID,
SHIPPINGCOST,
DESTINATION,
ROW_NUMBER() OVER (PARTITION BY WAREHOUSE ORDER BY SHIPPINGCOST DESC) AS ROWNUM
FROM [dbo].[supply_chain_cleaned1])
SELECT 
WAREHOUSE,
TRANSPORTMODE,
ORDERID,
SHIPPINGCOST,
DESTINATION
FROM CTE
WHERE ROWNUM<=2

GO
CREATE VIEW VW_BAD_ROUTES AS
WITH ROUTESS AS(
SELECT DESTINATION,
TRANSPORTMODE,
SUM(CASE WHEN DELIVERYSTATUS='DELAYED' THEN 1 ELSE 0 END) AS COMENZI_INTARZIATE,
DENSE_RANK() OVER (ORDER BY SUM(CASE WHEN DELIVERYSTATUS='DELAYED' THEN 1 ELSE 0 END)DESC) AS RANK_INTARZIERI
FROM [dbo].[supply_chain_cleaned1]
GROUP BY DESTINATION, TRANSPORTMODE)
SELECT 
DESTINATION,
TRANSPORTMODE,
COMENZI_INTARZIATE,
RANK_INTARZIERI
FROM ROUTESS
WHERE RANK_INTARZIERI<=5

